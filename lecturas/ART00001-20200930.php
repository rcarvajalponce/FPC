              <div class="pre-title wow fadeInLeft" data-wow-delay=".1s">Descripción General</div>
              <h2 class="wow fadeInRight" data-wow-delay=".2s">Reflexiones sobre la Condición del Cristiano</h2>
              <p class="text-sm wow fadeInUp" data-wow-delay=".3s"><p class="MsoNormal" style="line-height: normal; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">Gálatas 3:19
es claro cuando habla del propósito de la ley: <i><span style="color: red;">&#8220;ENTONCES,
&#191;PARA QUÉ SIRVE LA LEY? FUE AÑADIDA A CAUSA DE LAS TRANSGRESIONES, HASTA QUE
VINIESE LA SIMIENTE A QUIEN FUE HECHA LA PROMESA; Y FUE ORDENADA POR MEDIO DE
ÁNGELES EN MANO DE UN MEDIADOR&#8221;. </span></i></span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">1)&nbsp;&nbsp; Jesucristo, como único sin pecado original.&nbsp; Mateo
5:17 dice <i><span style="color: #cc0000;">"No piensen que he venido a
anular la ley o los profetas; no he venido a anularlos sino a darles
cumplimiento&#8221;</span></i>. Tomemos el texto en contexto: Jesús, como judío, está
hablando para judíos, regidos por la ley de Moisés (hasta la fecha). La ley fue
establecida exclusivamente como ya lo hemos estudiado para los judíos. En este
texto, Jesús, en vivo, en carne, y pueden leer los versículos que siguen, dice:
&#8220;que la ley no va a cambiar para ustedes (judíos)&#8221;. El no podía decirles, vengo
a quitar la ley para suavizarles la vida, porque justamente, la ley Dios la
había establecido para que reconocieran que eran pecadores y necesitaban un
redentor. En cambio, dijo que venía a cumplirla. Y repito, Jesús está hablando
como judío para judíos. Él estaba diciendo: véanme, yo soy el Cordero Perfecto,
el Hijo de Dios, yo soy el esperado. Sin embargo, muy pocos entendieron.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">2)&nbsp;&nbsp; Estamos de acuerdo en que Jesús vino y pudo cumplir la
ley, sin embargo, es de sorprender que Dios, en Éxodo 20:8-11 hable acerca del
sábado y establezca ese día como día de descanso, y Jesús (no Pablo o Pedro),
diga en Mateo 12:12<i><span style="color: #cc0000;"> &#8220;&#161;Cuánto más vale un hombre
que una oveja! Por lo tanto, está permitido hacer el bien en sábado&#8221; </span></i>&#191;Será
que Jesús a pesar de que dijo que solo hacía la voluntad de Su Padre, de manera
deliberada, casi como reto, estaba diciendo lo contrario? No, el solo estaba
profetizando acerca de lo que se aproximaba. Creo que, a través de todo su
ministerio, Jesús da muestras de lo que habría de venir, y esto, solo por su
sacrificio en la cruz.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">3)&nbsp;&nbsp; Solo para reflexión, han leído alguna vez el Antiguo
Testamento en la parte de los mandatos de Dios, temas sobre que hacer si se
siente duda de la esposa, o sobre los inmundos, lo que se ha de comer, la
obligación del diezmo o sobre la responsabilidad del pueblo de diezmar a los
levitas y estos a su vez a los sacerdotes. &#191;Podrían cumplir al pie de la
letra?&nbsp;</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">4)&nbsp;&nbsp; Con relación a los diez mandamientos (Éxodo 20:2-17) que
son considerados los &#8220;básicos&#8221; en la vida del creyente, has pensado &#191;cuántos
estamos cumpliendo? &#191;En cuantas ocasiones endiosas personas o cosas por encima
de Dios? &#191;En cuántas ocasiones mencionamos Su Nombre en vano? &#191;Y del día de
reposo? Y podemos seguir. Creo que estamos muy lejos de poder cumplir la ley.
Como dice Pablo, &#8220;Gracias a Dios por su Hijo Jesucristo&#8221;</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">5)&nbsp;&nbsp;&nbsp; Ahora, acerca de la vigencia de la ley en tiempo de
Gracia. Para esto, debemos establecer con claridad si creemos que Dios habló a
Pablo, Pedro, Santiago, Juan y el escritor de Hebreos. Si no creemos lo que
ellos nos predican, obviamente no nos quedará mas alternativa que vivir bajo la
ley de los judíos. Repito, si no creo que Jesucristo nos habla a través de
Pablo, obviamente voy a querer cumplir la ley porque sería lo que me queda para
agradar a Dios, aunque ya sabemos que es imposible de cumplir.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">Veamos
algunos versículos, que nos muestran la caducidad de la ley.&nbsp;</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">1)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Jesús dice en Mateo 5:18 Porque de
cierto os digo que hasta que pasen el cielo y la tierra, ni una jota ni una
tilde pasará de la ley, hasta que todo se haya cumplido; y Pablo dice en
Romanos 10:4 <i><span style="color: #cc0000;">&#8220;porque EL FIN DE LA LEY ES CRISTO,
PARA JUSTICIA A TODO AQUEL QUE CREE&#8221;</span></i>.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">2)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; En los siguientes versículos, por
cierto, dirigidos a los Hebreos (judíos), el escritor hace más patente la
caducidad de la ley.&nbsp; Hebreos 7:11-18 dice: <i><span style="color: #cc0000;">&#8220;Si,
pues, la perfección fuera por el sacerdocio levítico (porque bajo él recibió el
pueblo la ley), &#191;qué necesidad habría aún de que se levantase otro sacerdote,
según el orden de Melquisedec, y que no fuese llamado según el orden de Aarón?
Porque cambiado el sacerdocio, necesario es que haya también cambio de ley; y
aquel de quien se dice esto, es de otra tribu, de la cual nadie sirvió al
altar. Porque manifiesto es que nuestro Señor vino de la tribu de Judá, de la
cual nada habló Moisés tocante al sacerdocio. Y esto es aún más manifiesto, si
a semejanza de Melquisedec se levanta un sacerdote distinto, no constituido
conforme a la ley del mandamiento acerca de la descendencia, sino según el
poder de una vida indestructible. Pues se da testimonio de él: Tú eres
sacerdote para siempre, según el orden de Melquisedec. QUEDA, PUES, ABROGADO EL
MANDAMIENTO ANTERIOR A CAUSA DE SU DEBILIDAD E INEFICACIA&#8221;</span></i>. </span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">3)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Solo Cristo. <i><span style="color: #cc0000;">&#8220;Y a vosotros, estando muertos en pecados y en la incircuncisión de
vuestra carne, os dio vida juntamente con él, perdonándoos todos los pecados,
ANULANDO EL ACTA DE LOS DECRETOS QUE HABÍA CONTRA NOSOTROS, que nos era
contraria, quitándola de en medio y clavándola en la cruz. </span></i>Colosenses
2:13-14. </span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">4)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; <i><span style="color: #cc0000;">&#8220;Porque
él es nuestra paz, que de ambos pueblos hizo uno, derribando la pared
intermedia de separación, ABOLIENDO EN SU CARNE LAS ENEMISTADES, LA LEY DE LOS
MANDAMIENTOS EXPRESADOS EN ORDENANZAS, para crear en sí mismo de los dos un
solo y nuevo hombre, haciendo la paz&#8221;,</span></i> Efesios 2:14-15. Esta es la
ocasión tanto para judíos como para gentiles de tener paz con Dios.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">5)&nbsp;&nbsp;<i><span style="color: #cc0000;"> CRISTO NOS REDIMIÓ DE LA
MALDICIÓN DE LA LEY, hecho por nosotros maldición (porque está escrito: Maldito
todo el que es colgado en un madero.</span></i> Gálatas 3:13. Jesús nos libro
de la incapacidad o impotencia de cumplir la ley por medio de la obra de la
cruz.</span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; margin-left: 36pt; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify; text-indent: -18pt;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">6)&nbsp;&nbsp;&nbsp; El riesgo de pretender cumplir la ley, lo ilustra
muy bien Romanos 2:14-16,<i><span style="color: #cc0000;"> Porque cuando los
gentiles que no tienen ley, hacen por naturaleza lo que es de la ley, éstos,
AUNQUE NO TENGAN LEY, SON LEY PARA SÍ MISMOS, MOSTRANDO LA OBRA DE LA LEY
ESCRITA EN SUS CORAZONES, DANDO TESTIMONIO SU CONCIENCIA, Y ACUSÁNDOLES O
DEFENDIÉNDOLES SUS RAZONAMIENTOS, en el día en que Dios juzgará por Jesucristo
los secretos de los hombres, conforme a mi evangelio. Es decir que al que
pretenda vivir por la ley, de igual manera será juzgado por Dios bajo la ley.</span></i></span><span style="font-family: &quot;Times New Roman&quot;,serif; font-size: 12pt; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;"></span></p>

<p class="MsoNormal" style="line-height: normal; mso-margin-bottom-alt: auto; mso-margin-top-alt: auto; text-align: justify;"><span style="font-family: &quot;&quot;helvetica&quot;&quot;,serif; font-size: 12pt; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: ES-CR;">Termino
diciendo, no yo, el Señor por medio de Pablo.<i><span style="color: #cc0000;">
&#8220;No desecho la gracia de Dios; pues si por la ley fuese la justicia, entonces
por demás murió Cristo&#8221;.</span></i> Gálatas 2:21. Esto confirma una y otra vez
que la ley, aún después de Cristo no nos va a justificar y que por el contrario
