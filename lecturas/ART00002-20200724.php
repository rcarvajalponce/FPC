              <h2 class="wow fadeInRight" data-wow-delay=".2s">Mujeres con Propósito</h2>
              <p class="text-sm wow fadeInUp" data-wow-delay=".3s">
              <p class="MsoNormal" style="line-height: 115%;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Cuando encontramos el propósito de Dios para nuestras
vidas, toda nuestra existencia cobra sentido. Entendiendo la importancia de
esto, el grupo de mujeres de Familias para Cristo nos hacemos llamar: &#8220;<i>Mujeres
de propósito</i>&#8221;.</span></p>

<p class="MsoNormal" style="line-height: 115%;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Vivir no se trata de nacer, reproducirse y morir, sin embargo,
muchísimas mujeres alrededor del mundo se han conformado con eso.<span style="mso-spacerun: yes;">&nbsp; </span>El grupo de mujeres de Familias para Cristo
nos estamos dando a la tarea de renovar nuestra mentalidad bajo cinco
principios constantes:</span></p>

<p class="MsoListParagraphCxSpFirst" style="line-height: 115%; mso-list: l1 level1 lfo1; text-indent: -18.0pt;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">1-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp; </span></span></span><span style="color: #cc0000;"><span style="background-color: white;"><b><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Tengo un
propósito.</span></b></span></span><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;"><span style="mso-spacerun: yes;">&nbsp; </span><i>Efesios 2:10 &#8230;pues somos
hechura suya, creados en Cristo Jesús para buenas obras, las cuales Dios
preparó de antemano para que anduviéramos en ellas.</i></span></p>

<p class="MsoListParagraphCxSpMiddle" style="line-height: 115%; mso-list: l1 level1 lfo1; text-indent: -18.0pt;"><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">2-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp;
</span></span></span></i><span style="color: #cc0000;"><b><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Dios es bueno siempre.</span></b></span><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;"><span style="mso-spacerun: yes;"><span style="color: #cc0000;">&nbsp;</span> </span>1 Juan 3:1 <i>&#161;Fíjense qué gran amor nos ha
dado el Padre, que se nos llame hijos de Dios! &#161;Y lo somos! El mundo no nos
conoce, precisamente porque no lo conoció a él. &#161;Fíjense qué gran amor nos ha
dado el Padre, que se nos llame hijos de Dios! &#161;Y lo somos! El mundo no nos
conoce, precisamente porque no lo conoció a él.</i></span></p>

<p class="MsoListParagraphCxSpMiddle" style="line-height: 115%; mso-list: l1 level1 lfo1; text-indent: -18.0pt;"><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">3-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;<span style="color: #cc0000;">&nbsp;
</span></span></span></span></i><span style="color: #cc0000;"><b><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Nada es imposible</span></b></span><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;"><span style="color: #cc0000;">.</span> Mateo 19:26</span></i><span style="color: #cc0000; font-family: &quot;Arial&quot;,sans-serif;"> </span><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">&#8212;Para los
hombres es imposible&nbsp;&#8212;aclaró Jesús, mirándolos fijamente&#8212;,&nbsp;mas para
Dios todo es posible.</span></i></p>

<p class="MsoListParagraphCxSpMiddle" style="line-height: 115%; mso-list: l1 level1 lfo1; text-indent: -18.0pt;"><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">4-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp;<span style="color: #cc0000;">
</span></span></span></span></i><b><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;"><span style="color: #cc0000;">Soy responsable de mis decisiones</span>. </span></b><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Romanos 14:12</span></i><span lang="ES" style="color: #616161; font-family: &quot;Arial&quot;,sans-serif;"><span style="mso-spacerun: yes;">&nbsp;&nbsp; </span></span><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Así que cada uno de nosotros tendrá que dar cuentas de
sí a Dios.</span></i></p>

<p class="MsoListParagraphCxSpLast" style="line-height: 115%; mso-list: l1 level1 lfo1; text-indent: -18.0pt;"><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">5-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp; </span></span></span></i><b><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;"><span style="color: #cc0000;">La grandeza
viene a través del servicio.</span> </span></b><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Mateo 20:26-28<span style="mso-spacerun: yes;">&nbsp; </span><span style="mso-spacerun: yes;">&nbsp;</span>Pero entre ustedes no debe ser así. Al
contrario, el que quiera hacerse grande entre ustedes deberá ser su
servidor,&nbsp;y el que quiera ser el primero deberá ser&nbsp;esclavo&nbsp;de
los demás;&nbsp;así como el Hijo del hombre no vino para que le sirvan, sino
para servir y para dar su&nbsp;vida&nbsp;en rescate por muchos.</span></i></p>

<p class="MsoNormal" style="line-height: 115%;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Cuando el propósito de Dios es claro y nos decidimos a
caminar hacia él, también debemos poner la mano en nuestro corazón y despertar
los sueños que a través de los años han estado guardados ahí. Los sueños, metas
o deseos, o como queramos llamarlos, son las herramientas<span style="mso-spacerun: yes;">&nbsp; </span>que Dios usará en la construcción del
propósito personal eterno.</span></p>

<p class="MsoNormal" style="line-height: 115%;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">El enemigo más grande y poderoso contra el cual
debemos lidiar es el sistema de creencias, que, a través de los años y a partir
de la enseñanza de nuestros padres y maestros y las experiencias vividas, se ha
formado.<span style="mso-spacerun: yes;">&nbsp; </span>Doy dos ejemplos de esto, muy
comunes:</span></p>

<p class="MsoListParagraphCxSpFirst" style="line-height: 115%; mso-list: l0 level1 lfo2; text-indent: -18.0pt;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">1-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp; </span></span></span><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Mentalidad de
lotería.<span style="mso-spacerun: yes;">&nbsp; </span>Es creer que debemos recibir y
adaptarnos a todo lo que nos pase...<span style="mso-spacerun: yes;">&nbsp; </span>Sin
embargo, la Palabra de Dios nos reta a vivir poderosamente, usando la autoridad
que nos fue delegada por Jesús. Queremos ser protagonistas en &#8220;hacer cosas aún
mayores a las que Él hizo&#8221;. <span style="mso-spacerun: yes;">&nbsp;</span>Juan 14:12</span></p>

<p class="MsoListParagraphCxSpLast" style="line-height: 115%; mso-list: l0 level1 lfo2; text-indent: -18.0pt;"><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR; mso-fareast-font-family: Arial;"><span style="mso-list: Ignore;">2-<span style="font: 7.0pt &quot;Times New Roman&quot;;">&nbsp;&nbsp;&nbsp; </span></span></span><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Mentalidad de
saltamontes. Es creer que los obstáculos son tan grandes que la palabra de Dios
no se va a cumplir. Como los israelitas cuando iban a conquistar la tierra
prometida y solo dos de los espías que había enviado Moisés pudieron creer que,
a pesar de los gigantes que habitaban allí, Dios les entregaría esas
tierras.<span style="mso-spacerun: yes;">&nbsp; </span>Los diez restantes, se vieron
como saltamontes al compararse con ellos.<span style="mso-spacerun: yes;">&nbsp;
</span>El antídoto está en la palabra de Dios que nos dice que nuestra vida
está escondida con Cristo en Dios, que a la par de los gigantes estorbos podemos
confiar en el Señor.</span></p>

<p class="MsoNormal" style="line-height: 115%;"><span style="color: #073763;"><i><span style="font-family: &quot;Arial&quot;,sans-serif; mso-ansi-language: ES-CR;">Nuestra meta general es creer en lo que Dios dice
acerca de nosotros, en lo eterno, y no en lo que viene a nuestros cinco
sentidos, lo temporal. </span></i></span></p>                
